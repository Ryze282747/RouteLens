export default class MarkdownExporter {
  constructor() {
    this.destroyed = false;
  }

  async export(data, options = {}) {
    this.ensureActive();
    this.validateData(data);
    this.validateOptions(options);

    const routes = this.sortRoutes(data.routes);

    const title =
      typeof options.title === "string" && options.title.trim()
        ? options.title.trim()
        : "API Documentation";

    const lines = [
      `# ${this.escapeMarkdown(title)}`,
      "",
      `> Generated by RouteLens on ${new Date().toISOString()}`,
      "",
      `**Total routes:** ${routes.length}`,
      ""
    ];

    if (
      typeof options.description === "string" &&
      options.description.trim()
    ) {
      lines.push(
        this.escapeMarkdown(options.description.trim()),
        ""
      );
    }

    this.appendSummary(lines, routes);

    if (options.groupBy === "framework") {
      this.appendFrameworkGroups(lines, routes);
    } else if (options.groupBy === "file") {
      this.appendFileGroups(lines, routes);
    } else {
      this.appendMethodGroups(lines, routes);
    }

    if (options.includeAnalysis !== false) {
      this.appendAnalysis(lines, data);
    }

    return lines.join("\n").trimEnd() + "\n";
  }

  appendSummary(lines, routes) {
    const methodCounts = new Map();

    for (const route of routes) {
      for (const method of route.methods) {
        const normalized = String(method).trim().toUpperCase();

        if (!normalized) {
          continue;
        }

        methodCounts.set(
          normalized,
          (methodCounts.get(normalized) || 0) + 1
        );
      }
    }

    lines.push("## Summary", "");
    lines.push("| HTTP Method | Routes |");
    lines.push("| --- | ---: |");

    for (const [ method, count ] of [ ...methodCounts ].sort()) {
      lines.push(
        `| ${this.escapeTableCell(method)} | ${count} |`
      );
    }

    lines.push("");
  }

  appendMethodGroups(lines, routes) {
    const groups = this.groupRoutes(
      routes,
      (route) => route.methods.join(", ") || "Unknown"
    );

    lines.push("## Routes", "");

    for (const [ group, groupRoutes ] of groups) {
      lines.push(
        `### ${this.escapeMarkdown(group)}`,
        ""
      );

      for (const route of groupRoutes) {
        this.appendRoute(lines, route);
      }
    }
  }

  appendFrameworkGroups(lines, routes) {
    const groups = this.groupRoutes(
      routes,
      (route) => route.framework || "unknown"
    );

    lines.push("## Routes by Framework", "");

    for (const [ framework, groupRoutes ] of groups) {
      lines.push(
        `### ${this.escapeMarkdown(framework)}`,
        ""
      );

      for (const route of groupRoutes) {
        this.appendRoute(lines, route);
      }
    }
  }

  appendFileGroups(lines, routes) {
    const groups = this.groupRoutes(
      routes,
      (route) => route.file || "Unknown source"
    );

    lines.push("## Routes by Source File", "");

    for (const [ file, groupRoutes ] of groups) {
      lines.push(
        `### ${this.escapeMarkdown(file)}`,
        ""
      );

      for (const route of groupRoutes) {
        this.appendRoute(lines, route);
      }
    }
  }

  appendRoute(lines, route) {
    const methods = route.methods
      .map((method) => `\`${this.escapeCode(method)}\``)
      .join(", ");

    lines.push(
      `#### ${methods} ${this.escapeMarkdown(route.path)}`,
      ""
    );

    if (route.handler) {
      lines.push(
        `- **Handler:** ${this.toCodeSpan(route.handler)}`
      );
    }

    if (route.controller) {
      lines.push(
        `- **Controller:** ${this.toCodeSpan(route.controller)}`
      );
    }

    if (route.framework) {
      lines.push(
        `- **Framework:** ${this.escapeMarkdown(route.framework)}`
      );
    }

    if (route.file) {
      const location = route.line
        ? `${route.file}:${route.line}`
        : route.file;

      lines.push(
        `- **Source:** ${this.toCodeSpan(location)}`
      );
    }

    if (route.blueprint) {
      lines.push(
        `- **Blueprint:** ${this.toCodeSpan(route.blueprint)}`
      );
    }

    if (route.router) {
      lines.push(
        `- **Router:** ${this.toCodeSpan(route.router)}`
      );
    }

    lines.push("");
  }

  appendAnalysis(lines, data) {
    const duplicates = Array.isArray(data.duplicates)
      ? data.duplicates
      : [];

    const conflicts = Array.isArray(data.conflicts)
      ? data.conflicts
      : [];

    if (duplicates.length === 0 && conflicts.length === 0) {
      return;
    }

    lines.push("## Route Analysis", "");

    if (duplicates.length > 0) {
      lines.push("### Duplicate Routes", "");

      for (const duplicate of duplicates) {
        if (!duplicate || typeof duplicate !== "object") {
          continue;
        }

        const method = duplicate.method || "Unknown";
        const path = duplicate.path || "";

        const count = Number.isFinite(duplicate.count)
          ? duplicate.count
          : Array.isArray(duplicate.routes)
            ? duplicate.routes.length
            : 0;

        lines.push(
          `- **${this.escapeMarkdown(method)} ${this.escapeMarkdown(path)}** — ${count} declarations`
        );
      }

      lines.push("");
    }

    if (conflicts.length > 0) {
      lines.push("### Potential Conflicts", "");

      for (const conflict of conflicts) {
        if (!conflict || typeof conflict !== "object") {
          continue;
        }

        const type = conflict.type || "Conflict";
        const severity = conflict.severity || "unknown";
        const message =
          conflict.message || "Potential route conflict";

        lines.push(
          `- **${this.escapeMarkdown(type)}** (${this.escapeMarkdown(severity)} severity) — ${this.escapeMarkdown(message)}`
        );
      }

      lines.push("");
    }
  }

  groupRoutes(routes, getKey) {
    const groups = new Map();

    for (const route of routes) {
      const key = String(getKey(route));

      if (!groups.has(key)) {
        groups.set(key, []);
      }

      groups.get(key).push(route);
    }

    return [ ...groups.entries() ].sort(
      ([ first ], [ second ]) =>
        String(first).localeCompare(String(second))
    );
  }

  sortRoutes(routes) {
    return [ ...routes ].sort((first, second) => {
      const pathComparison = String(first.path).localeCompare(
        String(second.path)
      );

      if (pathComparison !== 0) {
        return pathComparison;
      }

      return String(first.methods.join(",")).localeCompare(
        String(second.methods.join(","))
      );
    });
  }

  escapeMarkdown(value) {
    return String(value)
      .replace(/\\/g, "\\\\")
      .replace(/\r\n?|\n/g, " ")
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/([`*_{}\[\]()#+\-.!|])/g, "\\$1");
  }

  escapeTableCell(value) {
    return String(value)
      .replace(/\\/g, "\\\\")
      .replace(/\r\n?|\n/g, " ")
      .replace(/&/g, "&amp;")
      .replace(/</g, "&lt;")
      .replace(/>/g, "&gt;")
      .replace(/\|/g, "\\|");
  }

  escapeCode(value) {
    return String(value)
      .replace(/\r\n?|\n/g, " ");
  }

  toCodeSpan(value) {
    const content = this.escapeCode(value);

    const backtickRuns = content.match(/`+/g) || [];

    const longestRun = backtickRuns.reduce(
      (longest, current) =>
        Math.max(longest, current.length),
      0
    );

    const delimiter = "`".repeat(longestRun + 1);

    const needsPadding =
      content.startsWith("`") ||
      content.endsWith("`") ||
      (
        content.startsWith(" ") &&
        content.endsWith(" ") &&
        content.trim().length > 0
      );

    const padded = needsPadding
      ? ` ${content} `
      : content;

    return `${delimiter}${padded}${delimiter}`;
  }

  validateData(data) {
    if (
      !data ||
      typeof data !== "object" ||
      Array.isArray(data)
    ) {
      throw new TypeError(
        "Export data must be an object."
      );
    }

    if (!Array.isArray(data.routes)) {
      throw new TypeError(
        "Export data must contain a routes array."
      );
    }

    for (const route of data.routes) {
      if (
        !route ||
        typeof route !== "object" ||
        Array.isArray(route) ||
        typeof route.path !== "string" ||
        !Array.isArray(route.methods)
      ) {
        throw new TypeError(
          "Export data contains an invalid route."
        );
      }
    }
  }

  validateOptions(options) {
    if (
      !options ||
      typeof options !== "object" ||
      Array.isArray(options)
    ) {
      throw new TypeError(
        "Export options must be an object."
      );
    }
  }

  ensureActive() {
    if (this.destroyed) {
      throw new Error(
        "MarkdownExporter has been destroyed."
      );
    }
  }

  destroy() {
    this.destroyed = true;
  }
}
