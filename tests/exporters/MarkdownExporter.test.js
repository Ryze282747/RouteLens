import { describe, it, expect, beforeEach } from "vitest";
import MarkdownExporter from "../../src/exporters/MarkdownExporter.js";

describe("MarkdownExporter", () => {
  let exporter;

  const sampleData = {
    project: {
      name: "Test Project"
    },
    routes: [
      {
        id: "route-1",
        path: "/users",
        methods: [ "GET" ],
        framework: "Flask",
        file: "app.py",
        line: 10,
        handler: "get_users"
      },
      {
        id: "route-2",
        path: "/users",
        methods: [ "POST" ],
        framework: "Flask",
        file: "app.py",
        line: 20,
        handler: "create_user"
      },
      {
        id: "route-3",
        path: "/products",
        methods: [ "GET" ],
        framework: "Express",
        file: "routes/products.js",
        line: 15,
        handler: "getProducts"
      }
    ],
    duplicates: [],
    conflicts: []
  };

  beforeEach(() => {
    exporter = new MarkdownExporter();
  });

  describe("export()", () => {
    it("should generate Markdown documentation", async () => {
      const result = await exporter.export(sampleData);

      expect(result).toContain("# API Documentation");
      expect(result).toContain("Generated by RouteLens");
      expect(result).toContain("**Total routes:** 3");
      expect(result).toContain("/users");
      expect(result).toContain("/products");
    });

    it("should include a custom title", async () => {
      const result = await exporter.export(sampleData, {
        title: "My API"
      });

      expect(result).toContain("# My API");
    });

    it("should include a custom description", async () => {
      const result = await exporter.export(sampleData, {
        description: "API documentation for testing."
      });

      expect(result).toContain(
        "API documentation for testing\\."
      );
    });

    it("should use a default title for an empty title", async () => {
      const result = await exporter.export(sampleData, {
        title: "   "
      });

      expect(result).toContain("# API Documentation");
    });

    it("should end the document with a newline", async () => {
      const result = await exporter.export(sampleData);

      expect(result.endsWith("\n")).toBe(true);
    });

    it("should reject invalid export data", async () => {
      await expect(
        exporter.export(null)
      ).rejects.toThrow("Export data must be an object.");
    });

    it("should reject data without a routes array", async () => {
      await expect(
        exporter.export({})
      ).rejects.toThrow(
        "Export data must contain a routes array."
      );
    });

    it("should reject invalid route entries", async () => {
      await expect(
        exporter.export({
          routes: [ { path: "/users", methods: "GET" } ]
        })
      ).rejects.toThrow(
        "Export data contains an invalid route."
      );
    });

    it("should reject invalid options", async () => {
      await expect(
        exporter.export(sampleData, null)
      ).rejects.toThrow(
        "Export options must be an object."
      );
    });

    it("should reject array options", async () => {
      await expect(
        exporter.export(sampleData, [])
      ).rejects.toThrow(
        "Export options must be an object."
      );
    });

    it("should reject exports after destruction", async () => {
      exporter.destroy();

      await expect(
        exporter.export(sampleData)
      ).rejects.toThrow(
        "MarkdownExporter has been destroyed."
      );
    });

    it("should prevent new Markdown headings from injected title newlines", async () => {
      const result = await exporter.export(sampleData, {
        title: "Safe Title\n## Injected Heading"
      });

      expect(result).toContain(
        "# Safe Title \\#\\# Injected Heading"
      );

      expect(result).not.toContain(
        "\n## Injected Heading"
      );
    });

    it("should escape HTML in custom descriptions", async () => {
      const result = await exporter.export(sampleData, {
        description: "<script>alert('test')</script> & content"
      });

      expect(result).toContain(
        "&lt;script&gt;alert\\('test'\\)&lt;/script&gt; &amp; content"
      );

      expect(result).not.toContain("<script>");
    });

    it("should flatten newlines in route paths", async () => {
      const data = {
        routes: [
          {
            path: "/users\n## Injected Heading",
            methods: [ "GET" ]
          }
        ]
      };

      const result = await exporter.export(data);

      expect(result).toContain(
        "/users \\#\\# Injected Heading"
      );

      expect(result).not.toContain(
        "\n## Injected Heading"
      );
    });
  });

  describe("summary", () => {
    it("should include HTTP method counts", async () => {
      const result = await exporter.export(sampleData);

      expect(result).toContain("| GET | 2 |");
      expect(result).toContain("| POST | 1 |");
    });

    it("should handle routes without methods", async () => {
      const data = {
        routes: [
          {
            path: "/health",
            methods: []
          }
        ]
      };

      const result = await exporter.export(data);

      expect(result).toContain("**Total routes:** 1");
    });

    it("should escape table cell separators", async () => {
      const data = {
        routes: [
          {
            path: "/users",
            methods: [ "GET|POST" ]
          }
        ]
      };

      const result = await exporter.export(data);

      expect(result).toContain("GET\\|POST");
    });

    it("should escape HTML characters in table cells", () => {
      const result = exporter.escapeTableCell(
        "<script>&value</script>"
      );

      expect(result).toBe(
        "&lt;script&gt;&amp;value&lt;/script&gt;"
      );
    });

    it("should flatten newlines in table cells", () => {
      const result = exporter.escapeTableCell(
        "GET\nPOST"
      );

      expect(result).toBe("GET POST");
    });
  });

  describe("grouping", () => {
    it("should group routes by HTTP methods by default", async () => {
      const result = await exporter.export(sampleData);

      expect(result).toContain("## Routes");
      expect(result).toContain("### GET");
      expect(result).toContain("### POST");
    });

    it("should group routes by framework", async () => {
      const result = await exporter.export(sampleData, {
        groupBy: "framework"
      });

      expect(result).toContain("## Routes by Framework");
      expect(result).toContain("### Flask");
      expect(result).toContain("### Express");
    });

    it("should group routes by source file", async () => {
      const result = await exporter.export(sampleData, {
        groupBy: "file"
      });

      expect(result).toContain("## Routes by Source File");
      expect(result).toContain("### app\\.py");
      expect(result).toContain("### routes/products\\.js");
    });

    it("should handle routes without framework names", async () => {
      const data = {
        routes: [
          {
            path: "/health",
            methods: [ "GET" ]
          }
        ]
      };

      const result = await exporter.export(data, {
        groupBy: "framework"
      });

      expect(result).toContain("### unknown");
    });

    it("should handle routes without source files", async () => {
      const data = {
        routes: [
          {
            path: "/health",
            methods: [ "GET" ]
          }
        ]
      };

      const result = await exporter.export(data, {
        groupBy: "file"
      });

      expect(result).toContain("### Unknown source");
    });

    it("should escape HTML in framework group names", async () => {
      const data = {
        routes: [
          {
            path: "/health",
            methods: [ "GET" ],
            framework: "<script>"
          }
        ]
      };

      const result = await exporter.export(data, {
        groupBy: "framework"
      });

      expect(result).toContain("### &lt;script&gt;");
      expect(result).not.toContain("<script>");
    });
  });

  describe("route details", () => {
    it("should include handler information", async () => {
      const result = await exporter.export(sampleData);

      expect(result).toContain("get_users");
      expect(result).toContain("create_user");
    });

    it("should include source file and line", async () => {
      const result = await exporter.export(sampleData);

      expect(result).toContain("app.py:10");
      expect(result).toContain("app.py:20");
    });

    it("should include optional routing information", async () => {
      const data = {
        routes: [
          {
            path: "/users",
            methods: [ "GET" ],
            blueprint: "api",
            router: "userRouter",
            controller: "UserController"
          }
        ]
      };

      const result = await exporter.export(data);

      expect(result).toContain("api");
      expect(result).toContain("userRouter");
      expect(result).toContain("UserController");
    });

    it("should flatten newlines in code span values", () => {
      const result = exporter.toCodeSpan(
        "first line\nsecond line"
      );

      expect(result).toBe(
        "`first line second line`"
      );
    });
  });

  describe("analysis", () => {
    it("should include duplicate route analysis", async () => {
      const data = {
        ...sampleData,
        duplicates: [
          {
            method: "GET",
            path: "/users",
            count: 2
          }
        ]
      };

      const result = await exporter.export(data);

      expect(result).toContain("### Duplicate Routes");
      expect(result).toContain("2 declarations");
    });

    it("should include conflict analysis", async () => {
      const data = {
        ...sampleData,
        conflicts: [
          {
            type: "exact",
            severity: "high",
            message: "Both routes use the same path."
          }
        ]
      };

      const result = await exporter.export(data);

      expect(result).toContain("### Potential Conflicts");
      expect(result).toContain("high severity");
    });

    it("should omit analysis when disabled", async () => {
      const data = {
        ...sampleData,
        duplicates: [
          {
            method: "GET",
            path: "/users",
            count: 2
          }
        ]
      };

      const result = await exporter.export(data, {
        includeAnalysis: false
      });

      expect(result).not.toContain("## Route Analysis");
    });

    it("should omit analysis section when no findings exist", async () => {
      const result = await exporter.export(sampleData);

      expect(result).not.toContain("## Route Analysis");
    });

    it("should safely handle malformed analysis entries", async () => {
      const data = {
        ...sampleData,
        duplicates: [ null, "invalid" ],
        conflicts: [ null, "invalid" ]
      };

      const result = await exporter.export(data);

      expect(result).toContain("## Route Analysis");
    });

    it("should escape HTML in conflict messages", async () => {
      const data = {
        routes: [],
        conflicts: [
          {
            type: "unsafe <type>",
            severity: "high",
            message: "<script>alert('test')</script>"
          }
        ]
      };

      const result = await exporter.export(data);

      expect(result).toContain(
        "&lt;script&gt;alert\\('test'\\)&lt;/script&gt;"
      );

      expect(result).not.toContain("<script>");
    });
  });

  describe("escaping", () => {
    it("should escape Markdown special characters", () => {
      const result = exporter.escapeMarkdown(
        "test *bold* [link] | value"
      );

      expect(result).toContain("\\*");
      expect(result).toContain("\\[");
      expect(result).toContain("\\|");
    });

    it("should escape backslashes", () => {
      const result = exporter.escapeMarkdown(
        "folder\\file"
      );

      expect(result).toContain("\\\\");
    });

    it("should escape HTML-sensitive characters", () => {
      const result = exporter.escapeMarkdown(
        "<script>&value</script>"
      );

      expect(result).toBe(
        "&lt;script&gt;&amp;value&lt;/script&gt;"
      );
    });

    it("should flatten newlines", () => {
      const result = exporter.escapeMarkdown(
        "first line\nsecond line"
      );

      expect(result).toBe(
        "first line second line"
      );
    });

    it("should create safe inline code spans containing backticks", () => {
      const result = exporter.toCodeSpan(
        "value`with`backticks"
      );

      expect(result).toBe(
        "``value`with`backticks``"
      );
    });

    it("should handle empty code span values", () => {
      expect(exporter.toCodeSpan("")).toBe("``");
    });

    it("should preserve HTML-like text safely inside code spans", () => {
      const result = exporter.toCodeSpan(
        "<script>alert('test')</script>"
      );

      expect(result).toBe(
        "`<script>alert('test')</script>`"
      );
    });
  });

  describe("lifecycle", () => {
    it("should destroy safely more than once", () => {
      expect(() => {
        exporter.destroy();
        exporter.destroy();
      }).not.toThrow();
    });
  });
});
